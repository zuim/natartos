static const uint8_t *glyph(char c) {
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    for (size_t i = 0; i < sizeof(FONT) / sizeof(FONT[0]); i++)
        if (FONT[i].c == c) return FONT[i].rows;
    return NULL;
}

/* width in pixels of `s` at `scale` (5 px glyph + 1 px gap) */
int fbtext_width(const char *s, int scale) { return (int)strlen(s) * 6 * scale - scale; }

/* draw into one BGRA slot */
void fbtext_draw(uint8_t *slot, int fw, int fh, int x, int y, int scale, const char *s, uint32_t bgra) {
    uint32_t *px = (uint32_t *)slot;
    for (; *s; s++, x += 6 * scale) {
        const uint8_t *g = glyph(*s);
        if (!g) continue;
        for (int r = 0; r < 7; r++)
            for (int col = 0; col < 5; col++) {
                if (!(g[r] & (0x10 >> col))) continue;
                for (int dy = 0; dy < scale; dy++) {
                    int yy = y + r * scale + dy;
                    if (yy < 0 || yy >= fh) continue;
                    for (int dx = 0; dx < scale; dx++) {
                        int xx = x + col * scale + dx;
                        if (xx >= 0 && xx < fw) px[(size_t)yy * fw + xx] = bgra;
                    }
                }
            }
    }
}
