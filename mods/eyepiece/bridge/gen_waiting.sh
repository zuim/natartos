# Regenerate waiting_h264.h: the "waiting for the PC" screen as one H.264 IDR
# access unit per variant (with / without the Back hint). The bridge decodes it
# like a PC frame and shows it on the VIDEO0 plane, so the GUI's own buffers are
# never painted. Needs gcc, ffmpeg with libx264 and xxd; the output is committed,
# so normal builds (build.sh) don't need any of them.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
T="$(mktemp -d)"; trap 'rm -rf "$T"' EXIT
gcc -O2 -o "$T/gen" "$HERE/gen_waiting.c" "$HERE/fbtext.c"
out="$HERE/waiting_h264.h"
{
  echo "/* generated by gen_waiting.sh — do not edit */"
  for v in 0 1; do
    "$T/gen" $v | ffmpeg -loglevel error -f rawvideo -pix_fmt bgra -s 1920x1080 -i - -frames:v 1 \
      -c:v libx264 -profile:v high -level 5.1 -pix_fmt yuv420p -preset veryslow -crf 18 \
      -x264-params keyint=1:repeat-headers=1 -bsf:v h264_metadata=aud=remove -f h264 "$T/w$v.h264"
    (cd "$T" && xxd -i -n "waiting_h264_back$v" "w$v.h264")
  done
} > "$out"
grep -E "_len =" "$out"
